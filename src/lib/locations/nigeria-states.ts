export function findNigerianStateByCode(code: string): NigerianState | undefined {
  return NIGERIAN_STATES.find((s) => s.code.toUpperCase() === code.trim().toUpperCase());
}

export function findNigerianStateByName(name: string): NigerianState | undefined {
  const needle = name.trim().toLowerCase();
  return NIGERIAN_STATES.find((s) => s.name.toLowerCase() === needle);
}
